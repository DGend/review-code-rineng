"""Re-score a batch run's cached poses with the current ergo_v2 tables.

batch_v1 was scored on 2026-05-14, before the 2026-08-11 tables.py correction
(RULA Table A cells that read one point low against McAtamney 1993). Pose
inference is unchanged, so this recomputes only the ergo score columns from
details/*.npz with the same score_all arguments batch_infer uses, and patches
them into summary.csv and summary_with_pred.csv (the process classifier is not
retrained). Downstream files are then regenerated by run_c3_mc ->
run_c4_calibration -> run_x_w_batch.

Usage: python -m ace_pose.rescore_batch --batch ace_pose/_runs/batch_v1
"""
from __future__ import annotations

import argparse
import os
from pathlib import Path

import numpy as np
import pandas as pd

import sys
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from ace_pose.batch_infer import ergo_columns
from ace_pose.ergo_v2.context_policy import cohort_context  # posture only, see context_policy
from ace_pose.ergo_v2.pipeline import score_all
from ace_pose.major_joints import Major25Pose

TARGETS = ("summary.csv", "summary_with_pred.csv")


def rescore(df: pd.DataFrame, details: Path) -> pd.DataFrame:
    rows = {}
    for r in df[df.status == "ok"].itertuples():
        d = np.load(details / f"{r.file_stem}.npz")
        pose = Major25Pose(keypoints=d["kpts_m25"].astype(np.float64),
                           confidence=d["conf_m25"].astype(np.float64),
                           source=np.zeros(25, dtype=np.int8))
        pid = getattr(r, "process_id", None)
        result = score_all(
            pose, world_up=np.array([0.0, -1.0, 0.0]), walking=False, **cohort_context(r.process_label),
            domain=r.domain, process_id=None if pd.isna(pid) else pid,
            process_label=r.process_label,
        )
        rows[r.file_stem] = ergo_columns(result)
    return pd.DataFrame.from_dict(rows, orient="index")


def patch(path: Path, new: pd.DataFrame) -> None:
    df = pd.read_csv(path)
    n0, stems0 = len(df), df.file_stem.tolist()
    ok = df.status == "ok"
    cols = [c for c in new.columns if c in df.columns]
    before = df.loc[ok, ["owas_action", "rula_action", "reba_action"]].copy()
    df.loc[ok, cols] = new.loc[df.loc[ok, "file_stem"], cols].to_numpy()
    assert len(df) == n0 and df.file_stem.tolist() == stems0
    after = df.loc[ok, ["owas_action", "rula_action", "reba_action"]]
    changed = {c: int((before[c].astype(int) != after[c].astype(int)).sum()) for c in before}
    tmp = path.with_suffix(path.suffix + ".tmp")
    df.to_csv(tmp, index=False)
    os.replace(tmp, path)
    print(f"{path.name}: {len(cols)} score columns patched on {int(ok.sum())} rows; "
          f"action levels changed {changed}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--batch", type=Path, required=True)
    args = ap.parse_args()
    base = pd.read_csv(args.batch / "summary.csv")
    new = rescore(base, args.batch / "details")
    for name in TARGETS:
        patch(args.batch / name, new)


if __name__ == "__main__":
    main()
